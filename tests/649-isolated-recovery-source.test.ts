import {readFileSync} from 'node:fs';
import {describe,expect,it} from 'vitest';

const read=(path:string)=>readFileSync(path,'utf8');
const script=read('scripts/isolated-full-recovery-e2e.mjs');
const flow=read('.github/workflows/real-stack-e2e.yml');
const doc=read('docs/ISOLATED_POSTGRES_STORAGE_RECOVERY.md');
const packageJson=JSON.parse(read('package.json')) as {scripts?:Record<string,string>};

describe('#649 I18.02 isolated PostgreSQL+Storage independent checkpoint proof',()=>{
  it('refuses arbitrary, production, non-CI and unapproved environments before any dump/restore',()=>{
    expect(script).toContain("process.env.CI!=='true'");
    expect(script).toContain("process.env.MYFINHUB_ISOLATED_RECOVERY!=='1'");
    expect(script).toContain("projectId!=='rheomiq'");
    expect(script).toContain("container='supabase_db_'+projectId");
    expect(script).toContain("http:\\/\\/127\\.0\\.0\\.1:54321");
    expect(script).not.toContain('--linked');
    expect(script).not.toContain('db reset');
    expect(script).not.toContain('SUPABASE_ACCESS_TOKEN');
    expect(script).not.toContain('process.env.DATABASE_URL');
  });
  it('takes a transferable custom DB dump, restores only into scratch DB, verifies history, RLS and leaves source intact',()=>{
    expect(script).toContain("'pg_dump'");
    expect(script).toContain("'-Fc'");
    expect(script).toContain("'template0',scratch");
    expect(script).toContain("create schema if not exists public;");
    expect(script).toContain("to_regnamespace('public')");
    expect(script).not.toContain("drop schema if exists public cascade");
    expect(script).not.toContain("'template1',scratch");
    expect(script).toContain("'--exit-on-error'");
    expect(script).toContain("const scratchRestoreRole='supabase_admin'");
    expect(script).toContain("current_setting('is_superuser')='on'");
    expect(script).toContain("'Disposable local Supabase privileged restore role is unavailable.'");
    expect(script).toContain("database===scratch?scratchRestoreRole:'postgres'");
    expect(script).toContain("db(['pg_restore','-U',scratchRestoreRole,'-d',scratch,'--exit-on-error'");
    expect(script).not.toContain("db(['pg_restore','-U','postgres','-d',scratch");
    expect(script).not.toContain('alter role postgres');
    expect(script).toContain("archiveDigest");
    expect(script).toContain("fingerprints(scratch)");
    expect(script).toContain("fingerprints('postgres')");
    expect(script).toContain("sourceRls===restoredRls");
    expect(script).toContain("'auth.users'");
    expect(script).toContain("['public.rheomiq_artwork_upload_intents','intent_id']");
    expect(script).toContain("'storage.objects'");
    expect(script).toContain("'supabase_migrations.schema_migrations'");
    expect(script).toContain("'dropdb','-U','postgres','--if-exists',scratch");
    expect(script).not.toContain("'dropdb','-U','postgres','--if-exists','postgres'");
  });
  it('replays every sampled Storage binary from a separate disk checkpoint into a disposable bucket with SHA-256 verification',()=>{
    expect(script).toContain("snapshot.push");
    expect(script).toContain("const sourceBucket='myfinhub-ci-source-'+process.pid");
    expect(script).toContain("sourceBucketCreated=true");
    expect(script).toContain("sourceBucketCleaned");
    expect(script).toContain("object/authenticated/");
    expect(script).toContain("fingerprints('postgres'))===JSON.stringify(pristine)");
    expect(script).toContain("await cleanupSourceBucket()");
    expect(script).toContain("writeFileSync(filename,bytes,{mode:0o600})");
    expect(script).toContain("total<=64*1024*1024");
    expect(script).toContain("arrayBuffer()");
    expect(script).toContain("sha(Buffer.from(await verified.arrayBuffer()))===item.hash");
    expect(script).toContain("await cleanupBucket()");
    expect(script).toContain("rmSync(tmp,{recursive:true,force:true");
  });
  it('classifies actual unregistered objects without authorizing deletion of inventory rows',()=>{
    const inventory=read('scripts/recovery-fixtures/artwork-storage-inventory.sql');
    expect(inventory).toContain('begin transaction isolation level repeatable read read only');
    expect(inventory).toContain('set local row_security = off');
    expect(inventory).toContain('public.rheomiq_financial_provider_assets');
    expect(inventory).toContain('public.rheomiq_recurring_service_assets');
    expect(inventory).toContain('from storage.objects');
    expect(inventory).toContain('full outer join registry_counts');
    expect(inventory).toContain('from public.rheomiq_history_points');
    expect(inventory).toContain('from public.rheomiq_backups');
    expect(inventory).toContain('from private.rheomiq_recurring');
    expect(inventory).toContain('from public.rheomiq_financial_provider_asset_bindings');
    expect(inventory).toContain('from recurring_reference_counts refs');
    expect(inventory).toContain('$.recurringOverrides.*.logoAssetKey');
    expect(inventory).toContain('$.recurringCustom[*].logoAssetKey');
    expect(inventory).toContain('$.recurring[*].logoAssetKey');
    expect(inventory).toContain("'recurringReferences'");
    expect(inventory).toContain("'providerReferences'");
    expect(script).toContain('MYFINHUB_QA_RELEASED_ARTWORK_KEYS');
    expect(script).toContain('match?.history_reference===true&&match.current_reference===false');
    expect(script).toContain('match.registry_count===0&&match.active_registry_count===0&&match.object_count===0');
    expect(script).toContain('PASS retained history artwork references without registry or object');
    expect(read('scripts/real-stack-e2e.ts')).toContain("MYFINHUB_QA_RELEASED_ARTWORK_KEYS:[serviceAssetKey,replacementKey].join(',')");
    expect(inventory).toContain('count(*) filter (where active is true)');
    for(const classification of ['ambiguous-identity','storage-only-unregistered','registry-only-missing-object','registered-inactive','registered-active'])
      expect(inventory).toContain("'"+classification+"'");
    expect(inventory).not.toMatch(/(?:insert into|update\s+storage\.|delete from|truncate|create function|alter table|grant execute)/i);
    expect(script).toContain('const pristineArtwork=artworkInventory(\'postgres\')');
    expect(script).toContain('createdOrphans.push(item)');
    expect(script).toContain("matching[0].classification==='storage-only-unregistered'");
    expect(script).toContain('JSON.stringify(restoredArtwork)===JSON.stringify(sourceArtwork)');
    expect(script).toContain('const item=createdOrphans[0]');
    expect(script).toContain("JSON.stringify(artworkInventory('postgres'))===JSON.stringify(pristineArtwork)");
    expect(script).toContain('PASS read-only artwork orphan inventory');
    expect(doc).toContain('not deletion authorization');
  });
  it('is gated only by the existing disposable local Supabase CI workflow; distinguishes this proof from release authorization',()=>{
    expect(packageJson.scripts?.['qa:isolated-recovery']).toBe('node scripts/isolated-full-recovery-e2e.mjs');
    expect(flow).toContain('MYFINHUB_ISOLATED_RECOVERY:');
    expect(flow).toContain("MYFINHUB_ISOLATED_RECOVERY: '1'");
    expect(flow).toContain('npm run qa:real-stack');
    expect(read('scripts/real-stack-e2e.ts')).toContain('stage isolated-postgresql-storage-restore-before-browser');
    expect(flow).toContain('"$MYFINHUB_QA_SUPABASE_CLI" start');
    expect(script).toContain('process.env.MYFINHUB_QA_SUPABASE_CLI');
    expect(script).toContain("execFileSync(cli,['status','-o','json']");
    expect(script).not.toContain("execFileSync('npx'");
    expect(flow).toContain('stop --no-backup');
    expect(doc).toContain('production');
    expect(doc).toContain('PostgreSQL');
    expect(doc).toContain('Storage');
    expect(doc).toContain('separate');
    expect(doc).toContain('approval');
  });
});
