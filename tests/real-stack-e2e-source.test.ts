    expect(script).toContain('rheomiq_app_state');
    expect(script).toContain("finance_storage_mode==='relational_v1'");
    expect(script).not.toContain('ahsukppxwaiagampsuzb');
    expect(script).not.toContain('SUPABASE_ACCESS_TOKEN');
