    expect(qa).toContain('noticeContrast.ratio>=4.5&&noticeContrast.fontSize>=11.5');
    expect(qa).toContain("name.includes('-375-')");
    expect(qa).toContain('noticeContrast.textWidth>=260&&noticeContrast.stacked');
